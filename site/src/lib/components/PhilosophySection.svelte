  <div class="section-kicker mono">
    <span>01</span><span>THE PHILOSOPHY</span><span>—</span>
  </div>
  <div class="manifesto-grid">
    <h2 id="manifesto-title" class="section-heading reveal">
      A desktop is<br />a <em>personal</em><br />instrument.
    </h2>
    <div class="manifesto-copy reveal">
      <p class="lead-copy">
        MooriShell is an open-source desktop experience exploring a better way
        to work on Windows.
      </p>
      <p>
        Inspired by Linux workflows and Moroccan design, it brings existing
        tools together through customization, integration, and community.
        Windows stays the host. Your applications stay yours.
      </p>
      <div class="principle-list">
        <div>
          <span class="principle-index mono">A</span>
          <div>
            <strong>Keep the keys.</strong>
            <p>
              Own your workflow, shortcuts, and files. No black box between you
              and the machine.
            </p>
          </div>
        </div>
        <div>
          <span class="principle-index mono">B</span>
          <div>
            <strong>Compose, don&apos;t replace.</strong>
            <p>
              Independent tools form a workspace. Each can change without
              rebuilding the whole.
            </p>
          </div>
        </div>
        <div>
          <span class="principle-index mono">C</span>
          <div>
            <strong>Make it legible.</strong>
            <p>
              Configuration and automation should be inspectable, documented,
              and reversible.
            </p>
          </div>
        </div>
      </div>
    </div>
  </div>
</section>
